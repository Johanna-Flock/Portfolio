/**
 * Updates the website language based on the selected language.
 * Finds all elements with a matching translation key.
 * Updates text content or input placeholders accordingly.
 * Saves the selected language in localStorage for future visits.
 * Refreshes the currently displayed reference in the new language.
 */

function setLanguage(language) {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(element => {
        const key = element.dataset.i18n;
        if (translations[language][key]) {

            if (element.placeholder !== undefined && element.tagName !== "BUTTON") {
                element.placeholder = translations[language][key];
            }

            else {
                element.textContent = translations[language][key];
            }
        }

    });

    localStorage.setItem("language", language);
    showReference(currentReference);
}

/**
 * Determines the language to use when the page loads.
 * Retrieves the previously selected language from localStorage.
 * Falls back to English if no language has been saved.
 * Applies the selected language to all translated elements.
 */

const savedLanguage = localStorage.getItem("language") || "en";
setLanguage(savedLanguage);

/**
 * Handles clicks on the language selection buttons.
 * Gets the selected language from the button's data attribute.
 * Updates the website content to the selected language.
 * Removes the active state from all language buttons.
 * Highlights the currently selected language button.
 */

const languageButtons = document.querySelectorAll(".language_btn");
languageButtons.forEach(button => {
    button.addEventListener("click", () => {
        const language = button.dataset.language;
        setLanguage(language);
        languageButtons.forEach(btn => {
            btn.classList.remove("active_language_button");
        });
        button.classList.add("active_language_button");
    });
});

/**
 * Handles language selection in the mobile navigation menu.
 * Updates the website content to the selected language.
 * Highlights the currently selected language.
 * Closes the mobile menu after selecting a language.
 */

const mobileLanguageButtons = document.querySelectorAll(".mobile_language_switch [data-language]");
mobileLanguageButtons.forEach(button => {
    button.addEventListener("click", () => {
        const language = button.dataset.language;
        setLanguage(language);
        mobileLanguageButtons.forEach(btn => {
            btn.classList.remove("active_language_button");
        });
        button.classList.add("active_language_button");
        burgerMenu.classList.remove("open");
        mobileMenuOverlay.classList.remove("open");
        burgerMenu.setAttribute("aria-expanded", "false");
    });
});

/**
 * Sets the active state for the currently selected language.
 * Compares each button's language with the saved language.
 * Adds the active class to the matching language button.
 * Removes the active class from all other language buttons.
 */

languageButtons.forEach(button => {

    if (button.dataset.language === savedLanguage) {
        button.classList.add("active_language_button");
    }

    else {
        button.classList.remove("active_language_button");
    }

});